<#
===============================================================================
 SCRIPT NAME : Merge-IPUAssessments.ps1
 VERSION     : 1.3.0 (for Windows-IPU-Readiness-Assessment 4.0.1+)
 PURPOSE     : Combine the JSON results of many servers into one overview.
 RUNS ON     : Any Windows machine with Windows PowerShell 5.1 or PowerShell 7
               (an admin workstation or jump host - NOT on the assessed servers).
===============================================================================

.SYNOPSIS
    Reads every <Computer>-IPU-Assessment.json (and -IPU-PostUpgrade.json) in a
    folder and writes:
        IPU-Fleet-Overview.html   one row per server, worst first
        IPU-Fleet-Servers.csv     the same as a spreadsheet (opens in Excel)
        IPU-Fleet-Findings.csv    every BLOCKER/ACTION/WARNING/MANUAL finding,
                                  one row each, for filtering in Excel
        IPU-Fleet-Eol.csv         every product with an end-of-life date found on
                                  the servers, with its verdict and the servers
    The end-of-life verdicts come from eol-snapshot.json (-EolSnapshot, or next
    to this script, or in the input folder). The data is from endoflife.date,
    MIT licence. Without a snapshot the products are listed but not checked.

    BUILT FROM  : src/merge/*.ps1 and the shared part src/assessment/25-eol-core.ps1 by
    build/Build-Script.ps1. Do not edit this file by hand; edit the parts and rebuild.

.EXAMPLE
    .\Merge-IPUAssessments.ps1 -InputFolder 'D:\IPU\Results'
    .\Merge-IPUAssessments.ps1 -InputFolder 'D:\IPU\Results' -OutputFolder 'D:\IPU\Overview' -Mode Pre

.NOTES
    Collect the JSON files from the servers with the approved SA file-retrieval
    process into one folder first. Read-only for the input files.
    CSV files use ';' as separator by default, which Excel opens in columns
    where the list separator is ';' (common in European regional settings).
    Use -Delimiter ',' where the list separator is ','.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory=$true)][string]$InputFolder,
    [string]$OutputFolder = '',
    [ValidateSet('Pre','Post','All')][string]$Mode = 'All',
    [string]$Delimiter = ';',
    [switch]$IncludeRedacted,
    # End-of-life snapshot (eol-snapshot.json, ADR 0003). Blank = next to this
    # script, then in the input folder.
    [string]$EolSnapshot = ''
)
